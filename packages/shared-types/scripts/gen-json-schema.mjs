// Exports the shared contract registry to one JSON Schema document (ADR-0003):
//   Zod (src/contracts) → generated/json-schema/contracts.json → Pydantic (apps/ai-worker, via datamodel-codegen)
// Runs against the built package (dist/), so `build` must run first — turbo wires this.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { isDeepStrictEqual } from "node:util";
import { z } from "zod";
import { contractRegistry } from "../dist/index.js";

const outFile = join(import.meta.dirname, "..", "generated", "json-schema", "contracts.json");

/** @type {Record<string, unknown>} */
const defs = {};
const addDef = (name, schema) => {
  if (name in defs && !isDeepStrictEqual(defs[name], schema)) {
    throw new Error(
      `Conflicting JSON Schema definitions for "${name}"; give the schemas distinct ids.`,
    );
  }
  defs[name] = schema;
};

for (const [name, schema] of Object.entries(contractRegistry).sort(([a], [b]) =>
  a.localeCompare(b),
)) {
  const {
    $schema: _dialect,
    $defs = {},
    ...root
  } = z.toJSONSchema(schema, {
    target: "draft-2020-12",
    io: "output",
    unrepresentable: "throw",
  });
  // Registered contracts are named by their registry key; see the naming rules in registry.ts.
  if (root.$ref !== undefined) {
    throw new Error(
      `Contract "${name}" must not declare a root .meta({ id }); it is named by its registry key.`,
    );
  }
  for (const [defName, def] of Object.entries($defs)) addDef(defName, def);
  addDef(name, root);
}

const document = {
  $schema: "https://json-schema.org/draft/2020-12/schema",
  $comment:
    "GENERATED by packages/shared-types/scripts/gen-json-schema.mjs from the Zod contracts. Do not edit.",
  title: "ReadiContracts",
  $defs: Object.fromEntries(Object.entries(defs).sort(([a], [b]) => a.localeCompare(b))),
};

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, `${JSON.stringify(document, null, 2)}\n`);
console.log(`Wrote ${Object.keys(document.$defs).length} definitions to ${outFile}`);
